import PDFDocument from 'pdfkit';
import fs from 'fs';
import { getReportPath } from './storage.js';

export async function generatePdfReport(record) {
  const reportPath = getReportPath(record.reportId);
  const doc = new PDFDocument({ size: 'A4', margin: 40 });
  const writeStream = fs.createWriteStream(reportPath);
  doc.pipe(writeStream);

  doc.fontSize(18).text('IDENT AI Deepfake Detection Report', { align: 'center' }).moveDown(0.5);
  doc.fontSize(10).fillColor('gray').text(`Report ID: ${record.reportId}`, { align: 'left' });
  doc.text(`Prediction ID: ${record.id}`, { align: 'left' });
  doc.text(`Generated: ${new Date(record.created_at).toISOString()}`, { align: 'left' });
  doc.moveDown(1);

  doc.fontSize(12).fillColor('black').text('Summary', { underline: true });
  doc.fontSize(10).text(record.analysisSummary || '', { lineGap: 4 });
  doc.moveDown(0.5);

  doc.text('Forensic Result', { underline: true });
  doc.fontSize(10).text(`Prediction: ${record.prediction}`);
  doc.text(`Confidence: ${record.confidence}%`);
  doc.text(`Probability: ${record.probability}%`);
  doc.text(`Model: ${record.model_name}`);
  doc.text(`Media Type: ${record.media_type}`);
  doc.text(`File: ${record.filename} (${(record.file_size / 1024).toFixed(1)} KB)`);
  doc.text(`Processing Time: ${record.processing_time}s`);
  doc.moveDown(0.5);

  doc.text('AI Forensic Explanation', { underline: true });
  doc.fontSize(10).text(record.ai_summary || '', { lineGap: 4 });
  doc.moveDown(0.5);

  doc.text('Risk Level', { underline: true });
  doc.fontSize(10).text(record.ai_risk || 'UNKNOWN');
  doc.moveDown(0.5);

  doc.text('Recommendations', { underline: true });
  doc.fontSize(10).text(record.recommendations || '', { lineGap: 4 });
  doc.moveDown(0.5);

  doc.text('Evidence Summary', { underline: true });
  doc.fontSize(10).text(record.evidenceSummary || 'Not available', { lineGap: 4 });
  doc.moveDown(1);

  doc.fontSize(9).fillColor('gray').text('This report is generated by IDENT AI. The prediction is produced by XceptionNet. The AI assistant provides explanation only.', { align: 'center' });

  doc.end();

  await new Promise((resolve, reject) => {
    writeStream.on('finish', resolve);
    writeStream.on('error', reject);
  });

  return reportPath;
}
